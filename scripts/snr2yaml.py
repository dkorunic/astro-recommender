"""Build the optically detected remnants of Green's Catalogue of Galactic
Supernova Remnants (2024 October version, 310 SNRs) as an uptonight target
list, cross-identified with Gary Imm's Deep Sky Compendium.

    curl -o snr.tsv 'https://vizier.cds.unistra.fr/viz-bin/asu-tsv?-source=VII/297/snrs&-out.all&-out.max=1000&-oc.form=dec'
    # the detailed listings, snrs.G*.html from https://www.mrao.cam.ac.uk/surveys/snrs/
    # (or the Wayback Machine's 2025 copies), into one directory
    scripts/snr2yaml.py snr.tsv snrs/ IMM_Compendium_2026.xlsx > internal/catalog/targets/SNR.yaml

Standard library only. CDS VII/297 gives every remnant's position (J2000, to
1 s and 1'), its axes and other names; most remnants lie behind the Galactic
dust and are radio or X-ray only, so a remnant is kept only when its detailed
listing has an "Optical:" note (98 do; each reports emission, a few only
possible). Some Wayback Machine copies are gzip-compressed: gunzip them first.
The Compendium's supernova remnants within max(10', half the major axis) are
its parts (the Veil's NGC 6960, NGC 6992, ...), named in the description, and
the nearest one whose size is within 2x of the major axis is the remnant
itself, giving the magnitude, surface brightness and common name. Position
and axes stay Green's.
"""

import html
import json
import os
import re
import sys

from imm2yaml import designation, kind, num, position, rows, sexagesimal
from sharpless2yaml import sep

COUNT = 310
GLB = re.compile(r"G(\d+\.\d)([+-]\d+\.\d)")


def glb(s):
    """"G065.3+05.7" or "G65.3+5.7" -> (65.3, 5.7), the key both spellings share."""
    m = GLB.search(s)
    return (float(m.group(1)), float(m.group(2))) if m else None


def green(path):
    """VizieR rows: (name, RA deg, Dec deg, major, minor arcmin, other names)."""
    out, cols = [], None
    for line in open(path, encoding="utf-8"):
        f = [c.strip() for c in line.rstrip("\n").split("\t")]
        if line.startswith("#") or len(f) < 2:
            continue
        if cols is None:
            cols = {c: i for i, c in enumerate(f)}
        elif glb(f[cols["SNR"]]):
            ra = f[cols["RAJ2000"]].split()
            de = f[cols["DEJ2000"]]
            dec = (int(de[1:3]) + int(de[4:6]) / 60) * (-1 if de[0] == "-" else 1)
            major = float(f[cols["MajDiam"]])
            minor = float(f[cols["MinDiam"]]) if f[cols["MinDiam"]] else major
            out.append((f[cols["SNR"]], (int(ra[0]) + int(ra[1]) / 60 + int(ra[2]) / 3600) * 15, dec,
                        major, minor, [re.sub(r"^(NGC|IC)(?=\d)", r"\1 ", n.strip())  # "IC443" as the lists spell it
                                       for n in f[cols["Names"]].split(",") if n.strip()]))
    if len(out) != COUNT:
        sys.exit(f"error: want {COUNT} remnants, got {len(out)}")
    return out


def optical(directory):
    """(l, b) -> the detailed listing's "Optical:" note ("" when it has none)."""
    out = {}
    for name in os.listdir(directory):
        key = glb(name)
        if key:
            text = re.sub(r"<[^>]*>", " ", open(os.path.join(directory, name), encoding="latin-1").read())
            m = re.search(r"Optical:\s*(.*?)(?:\n\s*\n|\s+(?:X-ray|Distance|Radio|References|Infrared|Point sources?):)",
                          html.unescape(text), re.S)
            out[key] = " ".join(m.group(1).split()) if m else ""
    if len(out) != COUNT:
        sys.exit(f"error: want {COUNT} detailed listings, got {len(out)}")
    return out


def main():
    cat, notes = green(sys.argv[1]), optical(sys.argv[2])
    snrs = [r for r in rows(sys.argv[3]) if kind(r) == "Supernova Remnant"]
    q = lambda s: json.dumps(s, ensure_ascii=False)  # JSON strings are valid YAML
    print("# Generated by scripts/snr2yaml.py: the optically detected remnants of Green's Catalogue of")
    print("# Galactic Supernova Remnants (2024 October version, CDS VII/297), cross-identified with")
    print("# Gary Imm's Deep Sky Compendium (2026) - data (c) Gary Imm.")
    kept = 0
    for snr, ra, dec, major, minor, names in sorted(cat, key=lambda c: glb(c[0])):
        if not notes[glb(snr)]:
            continue
        near = sorted((r for r in snrs if sep(*position(r), ra, dec) <= max(10, major / 2)),
                      key=lambda r: sep(*position(r), ra, dec))
        kept += 1
        own = next((r for r in near if num(r.get("G")) and major / 2 <= num(r["G"]) <= major * 2), None)
        mag = surfbr = None
        desc = names + [designation(r["A"]) for r in near]
        if own:
            mag, surfbr = num(own.get("T")), num(own.get("U"))
            desc += re.split(r"\s*,\s*", " ".join((own.get("Q") or "").split()))
        desc = [d for d in dict.fromkeys(desc) if d and glb(d) != glb(snr)]
        print('- constellation: ""')  # the loader computes it from RA/Dec
        print(f"  dec: {q(sexagesimal(dec))}")
        print(f"  description: {q(', '.join(desc))}")
        print(f"  mag: {mag if mag is not None else -9999}")
        if minor < major:
            print(f"  minor: {minor}")
        print(f"  name: {q(f'SNR {snr}')}")
        print(f"  ra: {q(sexagesimal(ra, hours=True))}")
        print(f"  size: {major}")
        if surfbr is not None:
            print(f"  surfbr: {round(surfbr, 2)}")
        print('  type: "Supernova Remnant"')
    print(f"{kept} of {COUNT} remnants kept", file=sys.stderr)


if __name__ == "__main__":
    main()
