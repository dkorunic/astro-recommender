"""Write internal/stars/bsc.go, the stars of the Yale Bright Star Catalogue
(5th edition, CDS V/50) to V 4.0, which STAR names when one falls in a
target's frame.

    curl -o bsc.tsv 'https://vizier.cds.unistra.fr/viz-bin/asu-tsv?-source=V/50/catalog&-out=HR,Name,Vmag,_RAJ2000,_DEJ2000&Vmag=%3C%3D4.0&-out.max=unlimited'
    scripts/bsc2go.py bsc.tsv > internal/stars/bsc.go && gofmt -l internal/stars

Standard library only. The positions are J2000 at the J2000 epoch (proper
motion left out: Arcturus' 2.3"/yr moves it under a minute of arc by 2026);
the names are the Bayer letter in Greek with its superscript, else the
Flamsteed number, then the constellation (Name's fixed columns: Flamsteed
1-3, Bayer 4-6, superscript 7, constellation 8-10), else HR N; brightest
first.
"""

import sys

from vizier2yaml import num, table

MAX_MAG = 4.0

GREEK = {
    "Alp": "α", "Bet": "β", "Gam": "γ", "Del": "δ", "Eps": "ε", "Zet": "ζ", "Eta": "η", "The": "θ",
    "Iot": "ι", "Kap": "κ", "Lam": "λ", "Mu": "μ", "Nu": "ν", "Xi": "ξ", "Omi": "ο", "Pi": "π",
    "Rho": "ρ", "Sig": "σ", "Tau": "τ", "Ups": "υ", "Phi": "φ", "Chi": "χ", "Psi": "ψ", "Ome": "ω",
}
# HR numbers left out: T CrB, a recurrent nova the catalogue lists at its
# 1946 peak (V 2.0), near V 10 between outbursts.
SKIP = {"5958"}
SUPERSCRIPT = str.maketrans("123456789", "¹²³⁴⁵⁶⁷⁸⁹")


def name(hr, field):
    field = field.rjust(10)
    flamsteed, bayer, sup, con = field[0:3].strip(), field[3:6].strip(), field[6].strip(), field[7:10].strip()
    if bayer:
        return f"{GREEK[bayer]}{sup.translate(SUPERSCRIPT)} {con}"
    if flamsteed:
        return f"{flamsteed} {con}"
    return f"HR {hr}"


def main():
    stars = []
    for t in table(sys.argv[1]):
        mag = num(t["Vmag"])
        if mag is None or mag > MAX_MAG or t["HR"] in SKIP:
            continue
        stars.append((mag, name(t["HR"], t["Name"]), float(t["_RAJ2000"]), float(t["_DEJ2000"])))
    stars.sort(key=lambda s: (s[0], s[1]))
    print("// SPDX-FileCopyrightText: 2026 Dinko Korunic <dinko.korunic@gmail.com>")
    print("// SPDX-License-Identifier: MIT")
    print()
    print("// Code generated by scripts/bsc2go.py from the Yale Bright Star Catalogue (CDS V/50); DO NOT EDIT.")
    print()
    print("package stars")
    print()
    print(f"// bright holds the catalogue's {len(stars)} stars to V {MAX_MAG}, brightest first.")
    print("var bright = [...]Star{")
    for mag, n, ra, dec in stars:
        print(f'\t{{"{n}", {mag:.2f}, {ra:.6f}, {dec:.6f}}},')
    print("}")


if __name__ == "__main__":
    main()
