"""Build the RCW catalogue (Rodgers, Campbell & Whiteoak 1960) of 181 southern
H-alpha emission regions as an uptonight target list, cross-identified with
Gary Imm's Deep Sky Compendium.

    curl -o rcw.tsv 'https://vizier.cds.unistra.fr/viz-bin/asu-tsv?-source=VII/216/rcw&-out.all&-out.max=400&-out.add=_RAJ,_DEJ&-oc.form=dec'
    scripts/rcw2yaml.py rcw.tsv IMM_Compendium_2026.xlsx > internal/catalog/targets/RCW.yaml

Standard library only. CDS VII/216 gives every region's position (B1950 to
0.1 min and 1', precessed by VizieR to J2000), its axes and its NGC/IC/Gum
cross-identifications (parenthesised, uncertain ones and "Near" ones are
left out). RCW 116 is not in it. The Compendium rows carrying RCW N, by name,
alternative ID or the RCW column (BA), within max(20', half the major axis)
are its cross-identifications; one named or alternative-ID'd RCW N is the
region itself and gives the position, size (unless more than 4x off the
major axis: a part), type, magnitude, surface brightness and common name.
Without one, a type all the rows agree on is kept (RCW 16 holds the
planetary NGC 2452 and the H II region NGC 2467), else "Emission Nebula".
The minor axis is the RCW axis ratio times the size, when that size is
within 2x of the RCW major axis. The brightness class (v/b/m/f) is not a
magnitude and is left out.
"""

import json
import re
import sys

from imm2yaml import aliases, designation, kind, num, position, sexagesimal
from sharpless2yaml import sep

COUNT = 182
ABSENT = {116}  # not in VII/216
PREFIX = {"NGC": "NGC {}", "IC": "IC {}", "M": "M {}", "G": "Gum {}"}


def rcw(path):
    """RCW number -> (RA deg, Dec deg, major, minor arcmin, cross-IDs) from the VizieR TSV."""
    out, cols = {}, None
    for line in open(path, encoding="utf-8"):
        f = [c.strip() for c in line.rstrip("\n").split("\t")]
        if line.startswith("#") or len(f) < 2:
            continue
        if cols is None:
            cols = {c: i for i, c in enumerate(f)}
        elif f[cols["RCW"]].isdigit():
            out[int(f[cols["RCW"]])] = (float(f[cols["_RAJ2000"]]), float(f[cols["_DEJ2000"]]),
                                        float(f[cols["MajAxis"]]), float(f[cols["MinAxis"]]), cross_ids(f[cols["IDs"]]))
    if sorted(out) != [n for n in range(1, COUNT + 1) if n not in ABSENT]:
        sys.exit(f"error: want RCW 1-{COUNT} but {sorted(ABSENT)} once each, got {len(out)} rows")
    return out


def cross_ids(s):
    """"NGC6164,5; G34,5a" -> NGC 6164, NGC 6165, Gum 34, Gum 35a: a shorter
    number replaces the previous one's last digits."""
    s = re.sub(r"\([^)]*\)\??|Near \S+", " ", s)
    out = []
    for group in s.split(";"):
        prefix, prev = None, ""
        for tok in re.findall(r"[A-Z]+ ?\d+[a-z]?|\d+[a-z]?", group):
            m = re.fullmatch(r"([A-Z]+) ?(\d+[a-z]?)", tok)
            if m:
                prefix, tok = m.groups()
            elif prefix and len(re.sub(r"\D", "", tok)) < len(re.sub(r"\D", "", prev)):
                digits = re.sub(r"\D", "", prev)
                tok = digits[: len(digits) - len(re.sub(r"\D", "", tok))] + tok
            prev = tok
            if prefix in PREFIX:
                out.append(PREFIX[prefix].format(tok))
    return out


def itself(r, n):
    """Whether a Compendium row is RCW N by its name or alternative IDs."""
    ids = [r["A"]] + (r.get("R") or "").split(",")
    return any(re.sub(r"\s", "", i) == f"RCW{n}" for i in ids)


def main():
    cat, index = rcw(sys.argv[1]), aliases(sys.argv[2])
    q = lambda s: json.dumps(s, ensure_ascii=False)  # JSON strings are valid YAML
    print("# Generated by scripts/rcw2yaml.py: the RCW catalogue of southern H-alpha emission regions")
    print("# (Rodgers, Campbell & Whiteoak 1960, CDS VII/216), cross-identified with Gary Imm's")
    print("# Deep Sky Compendium (2026) - data (c) Gary Imm.")
    for n, (ra, dec, major, minor, ids) in sorted(cat.items()):
        rows = []
        # A row carries RCW N both as a name and in the BA column: once each.
        for r in {id(r): r for r in index.get(f"RCW {n}", []) + index.get(f"RCW{n}", [])}.values():
            d = sep(*position(r), ra, dec)
            if d <= max(20, major / 2):
                rows.append(r)
            else:
                print(f"warning: RCW {n}: Compendium {r['A'].strip()} is {d:.0f}' away, ignored", file=sys.stderr)
        rows.sort(key=lambda r: sep(*position(r), ra, dec))
        own = [r for r in rows if itself(r, n)]
        typ, mag, surfbr, size, desc = "Emission Nebula", None, None, major, []
        if own:
            r = own[0]
            ra, dec = position(r)
            typ, mag, surfbr = kind(r), num(r.get("T")), num(r.get("U"))
            if num(r.get("G")) and major / 4 <= num(r["G"]) <= major * 4:
                size = num(r["G"])
            nick = re.sub(r"\s*\(\d+ ?of ?\d+\)", "", " ".join((r.get("Q") or "").split()))
            desc = re.split(r"\s*,\s*", nick)
        elif rows and len({kind(r) for r in rows}) == 1:
            typ = kind(rows[0])
        desc = [designation(r["A"]) for r in rows] + ids + desc
        desc = [d for d in dict.fromkeys(desc) if d and re.sub(r"\s", "", d) != f"RCW{n}"]
        print('- constellation: ""')  # the loader computes it from RA/Dec
        print(f"  dec: {q(sexagesimal(dec))}")
        print(f"  description: {q(', '.join(desc))}")
        print(f"  mag: {mag if mag is not None else -9999}")
        # The RCW axis ratio, on the Compendium's size only when it is about
        # the same extent (RCW 138's 8'x4' is a part of the 30' Sh2-17).
        if minor < major and major / 2 <= size <= major * 2:
            print(f"  minor: {round(size * minor / major, 2)}")
        print(f"  name: {q(f'RCW {n}')}")
        print(f"  ra: {q(sexagesimal(ra, hours=True))}")
        print(f"  size: {size}")
        if surfbr is not None:
            print(f"  surfbr: {round(surfbr, 2)}")
        print(f"  type: {q(typ)}")


if __name__ == "__main__":
    main()
