// moonEcliptic returns the Moon's geocentric ecliptic longitude and latitude
// of date (radians) and its distance in Earth equatorial radii, t Julian
// centuries of TT from J2000.
func moonEcliptic(t float64) (float64, float64, float64) {
	sine := func(phi float64) float64 { return math.Sin(2 * math.Pi * phi) }
	frac := func(x float64) float64 { return x - math.Floor(x) }
	t2 := t * t
	s1 := sine(0.19833 + 0.05611*t)
	s2 := sine(0.27869 + 0.04508*t)
	s3 := sine(0.16827 - 0.36903*t)
	s4 := sine(0.34734 - 5.37261*t)
	s5 := sine(0.10498 - 5.37899*t)
	s6 := sine(0.42681 - 0.41855*t)
	s7 := sine(0.14943 - 5.37511*t)
	dl0 := 0.84*s1 + 0.31*s2 + 14.27*s3 + 7.26*s4 + 0.28*s5 + 0.24*s6
	dl := 2.94*s1 + 0.31*s2 + 14.27*s3 + 9.34*s4 + 1.12*s5 + 0.83*s6
	dls := -6.40*s1 - 1.89*s6
	df := 0.21*s1 + 0.31*s2 + 14.27*s3 - 88.70*s4 - 15.30*s5 + 0.24*s6 - 1.86*s7
	dd := dl0 - dls
	dgam := -3332e-9*sine(0.59734-5.37261*t) - 539e-9*sine(0.35498-5.37899*t) - 64e-9*sine(0.39943-5.37511*t)

	l0 := 2*math.Pi*frac(0.60643382+1336.85522467*t-0.00000313*t2) + dl0/arcsecPerRad
	l := 2*math.Pi*frac(0.37489701+1325.55240982*t+0.00002565*t2) + dl/arcsecPerRad
	ls := 2*math.Pi*frac(0.99312619+99.99735956*t-0.00000044*t2) + dls/arcsecPerRad
	f := 2*math.Pi*frac(0.25909118+1342.22782980*t-0.00000892*t2) + df/arcsecPerRad
	d := 2*math.Pi*frac(0.82736186+1236.85308708*t-0.00000397*t2) + dd/arcsecPerRad

	// ex[6+j][k] is e^(i·j·arg_k) × fac_k^|j|, for j up to each argument's
	// highest multiple; the others stay 0, as in the original.
	var ex [13][4]complex128
	args := [4]float64{l, ls, f, d}
	highest := [4]int{4, 3, 4, 6}
	facs := [4]float64{1.000002208, 0.997504612 - 0.002495388*t, 1.000002708 + 139.978*dgam, 1}
	for k, arg := range args {
		ex[6][k] = 1
		ex[7][k] = complex(facs[k]*math.Cos(arg), facs[k]*math.Sin(arg))
		for j := 2; j <= highest[k]; j++ {
			ex[6+j][k] = ex[5+j][k] * ex[7][k]
		}
		for j := 1; j <= highest[k]; j++ {
			ex[6-j][k] = cmplx.Conj(ex[6+j][k])
		}
	}
	term := func(i [4]int8) complex128 {
		return ex[6+i[0]][0] * ex[6+i[1]][1] * ex[6+i[2]][2] * ex[6+i[3]][3]
	}

	var dlam, ds, gam1c float64
	sinpi := 3422.7
	for _, t := range moonSols {
		z := term(t.i)
		dlam += t.l * imag(z)
		ds += t.s * imag(z)
		gam1c += t.g * real(z)
		sinpi += t.p * real(z)
	}
	var n float64
	for _, t := range moonNs {
		n += t.c * imag(term(t.i))
	}
	dlam += 0.82*sine(0.7736-62.5512*t) + 0.31*sine(0.0466-125.1025*t) +
		0.35*sine(0.5785-25.1042*t) + 0.66*sine(0.4591+1335.8075*t) +
		0.64*sine(0.3130-91.5680*t) + 1.14*sine(0.1480+1331.2898*t) +
		0.21*sine(0.5918+1056.5859*t) + 0.44*sine(0.5784+1322.8595*t) +
		0.24*sine(0.2275-5.7374*t) + 0.28*sine(0.2965+2.6929*t) +
		0.33*sine(0.3132+6.3368*t)
	s := f + ds/arcsecPerRad
	lat := (1.000002708+139.978*dgam)*(18518.511+1.189+gam1c)*math.Sin(s) - 6.24*math.Sin(3*s) + n

	return 2 * math.Pi * frac((l0+dlam/arcsecPerRad)/(2*math.Pi)), lat / arcsecPerRad, arcsecPerRad / (0.999953253 * sinpi)
}

// moon returns the Moon's geocentric RA and Dec of date (degrees) and its
// distance in Earth equatorial radii at t.
func moon(t time.Time) (float64, float64, float64) {
	n := DaysJ2000(t)
	lon, lat, dist := moonEcliptic((n + deltaT(n)/86400) / 36525)
	ra, dec := eclipticToEquatorial(lon, lat, n)

	return ra, dec, dist
}

// deltaT is TT − UT in seconds n days from J2000: Espenak and Meeus'
// polynomials (NASA's Five Millennium Canon of Solar Eclipses), every range
// as Astronomy Engine has them.
func deltaT(n float64) float64 {
	y := 2000 + (n-14)/365.24217
	switch {
	case y < -500:
		u := (y - 1820) / 100

		return -20 + 32*u*u
	case y < 500:
		return poly(y/100, 10583.6, -1014.41, 33.78311, -5.952053, -0.1798452, 0.022174192, 0.0090316521)
	case y < 1600:
		return poly((y-1000)/100, 1574.2, -556.01, 71.23472, 0.319781, -0.8503463, -0.005050998, 0.0083572073)
	case y < 1700:
		return poly(y-1600, 120, -0.9808, -0.01532, 1/7129.0)
	case y < 1800:
		return poly(y-1700, 8.83, 0.1603, -0.0059285, 0.00013336, -1/1174000.0)
	case y < 1860:
		return poly(y-1800, 13.72, -0.332447, 0.0068612, 0.0041116, -0.00037436, 0.0000121272, -0.0000001699, 0.000000000875)
	case y < 1900:
		return poly(y-1860, 7.62, 0.5737, -0.251754, 0.01680668, -0.0004473624, 1/233174.0)
	case y < 1920:
		return poly(y-1900, -2.79, 1.494119, -0.0598939, 0.0061966, -0.000197)
	case y < 1941:
		return poly(y-1920, 21.20, 0.84493, -0.076100, 0.0020936)
	case y < 1961:
		return poly(y-1950, 29.07, 0.407, -1/233.0, 1/2547.0)
	case y < 1986:
		return poly(y-1975, 45.45, 1.067, -1/260.0, -1/718.0)
	case y < 2005:
		return poly(y-2000, 63.86, 0.3345, -0.060374, 0.0017275, 0.000651814, 0.00002373599)
	case y < 2050:
		return poly(y-2000, 62.92, 0.32217, 0.005589)
	case y < 2150:
		u := (y - 1820) / 100

		return -20 + 32*u*u - 0.5628*(2150-y)
	default:
		u := (y - 1820) / 100

		return -20 + 32*u*u
	}
}

// poly is c[0] + c[1]u + c[2]u² + ..., by Horner's rule.
func poly(u float64, c ...float64) float64 {
	v := 0.0
	for _, v0 := range slices.Backward(c) {
		v = v*u + v0
	}

	return v
}
